"""JobSource adapter interface.

Every external provider (Adzuna today; JSearch or Jooble later) implements
`JobSource.fetch()` and returns `NormalizedJob` records. `app.services.ingest`
upserts them into `jobs`, keyed on (source, external_id). The app always reads
from our own database, so it keeps working when a provider is slow or down.

Only official APIs, used within their terms. No scraping.
"""

from __future__ import annotations

import html
import re
from abc import ABC, abstractmethod
from dataclasses import dataclass, field
from datetime import datetime, timezone

import httpx

from app.config import get_settings
from app.services.resume import detect_skills


@dataclass
class NormalizedJob:
    source: str
    external_id: str
    title: str
    company: str
    location: str
    work_mode: str  # "" when unknown
    job_type: str  # "" when unknown
    salary_min_lpa: int | None
    salary_max_lpa: int | None
    exp_min: int | None
    exp_max: int | None
    description: str
    posted_at: datetime
    responsibilities: list[str] = field(default_factory=list)
    skills: list[str] = field(default_factory=list)
    apply_url: str | None = None
    salary_estimated: bool = False


class SourceNotConfigured(RuntimeError):
    pass


class SourceError(RuntimeError):
    """The provider answered with an error, or not at all."""


class JobSource(ABC):
    name: str

    @abstractmethod
    def is_configured(self) -> bool: ...

    @abstractmethod
    def fetch(self, query: str, location: str = "", page: int = 1) -> list[NormalizedJob]: ...


class SeedJobSource(JobSource):
    """Offline sample data generated by app.seed. Always available."""

    name = "seed"

    def is_configured(self) -> bool:
        return True

    def fetch(self, query: str, location: str = "", page: int = 1) -> list[NormalizedJob]:
        from app.seed import generate_jobs

        return [j for j in generate_jobs() if query.lower() in j.title.lower()][(page - 1) * 50 : page * 50]


# ---------- Adzuna ----------

# Adzuna spells some cities the old way; our location filter uses the current names.
CITY_NAMES = {
    "bangalore": "Bengaluru",
    "gurgaon": "Gurugram",
    "bombay": "Mumbai",
    "madras": "Chennai",
    "calcutta": "Kolkata",
    "new delhi": "Delhi",
}

_EXP = re.compile(r"(\d{1,2})\s*(?:\+|plus)?\s*(?:-|to|–)?\s*(\d{1,2})?\s*\+?\s*(?:years?|yrs?)", re.IGNORECASE)


def _clean(text: str) -> str:
    text = html.unescape(re.sub(r"<[^>]+>", " ", text or ""))
    return re.sub(r"\s+", " ", text).strip()


def _location(raw: dict) -> str:
    name = (raw.get("display_name") or "").strip()
    first, *rest = [p.strip() for p in name.split(",")] if name else [""]
    first = CITY_NAMES.get(first.lower(), first)
    if not first:
        return "India"
    return f"{first}, India" if first.lower() != "india" else "India"


def _work_mode(text: str) -> str:
    t = text.lower()
    if "hybrid" in t:
        return "Hybrid"
    if re.search(r"\b(remote|work from home|wfh)\b", t):
        return "Remote"
    return ""


def _job_type(raw: dict, title: str) -> str:
    if re.search(r"\bintern(ship)?\b", title, re.IGNORECASE):
        return "Internship"
    if raw.get("contract_type") == "contract":
        return "Contract"
    if raw.get("contract_time") == "part_time":
        return "Part-time"
    if raw.get("contract_time") == "full_time" or raw.get("contract_type") == "permanent":
        return "Full-time"
    return ""


def _experience(text: str) -> tuple[int | None, int | None]:
    m = _EXP.search(text)
    if not m:
        return None, None
    lo = int(m.group(1))
    hi = int(m.group(2)) if m.group(2) else None
    if lo > 30 or (hi is not None and (hi > 40 or hi < lo)):
        return None, None
    return lo, hi if hi is not None else lo + 3


def _lpa(value) -> int | None:
    """Adzuna India salaries are annual rupees; the app shows lakhs per annum."""
    try:
        v = float(value)
    except (TypeError, ValueError):
        return None
    if v <= 0:
        return None
    return max(1, round(v / 100_000))


def normalize_adzuna(raw: dict) -> NormalizedJob | None:
    title = _clean(raw.get("title", ""))[:160]
    company = _clean((raw.get("company") or {}).get("display_name", ""))[:120]
    ext_id = str(raw.get("id") or "")
    if not title or not company or not ext_id:
        return None
    description = _clean(raw.get("description", ""))
    text = f"{title} {description}"
    smin, smax = _lpa(raw.get("salary_min")), _lpa(raw.get("salary_max"))
    if smin and not smax:
        smax = smin
    if smax and not smin:
        smin = smax
    exp_min, exp_max = _experience(text)
    try:
        posted = datetime.fromisoformat(str(raw.get("created", "")).replace("Z", "+00:00"))
    except ValueError:
        posted = datetime.now(timezone.utc)
    url = raw.get("redirect_url") or None
    return NormalizedJob(
        source="adzuna",
        external_id=ext_id,
        title=title,
        company=company,
        location=_location(raw.get("location") or {}),
        work_mode=_work_mode(text),
        job_type=_job_type(raw, title),
        salary_min_lpa=smin,
        salary_max_lpa=smax,
        salary_estimated=str(raw.get("salary_is_predicted", "0")) == "1",
        exp_min=exp_min,
        exp_max=exp_max,
        description=description or "The employer's full description is on the original posting.",
        posted_at=posted,
        skills=detect_skills(text)[:10],
        apply_url=url if url and url.startswith("https://") else None,
    )


class AdzunaJobSource(JobSource):
    """Adzuna job search API for India: https://developer.adzuna.com/

    Free tier: 25 calls a minute and 250 a day. Results must credit "Jobs by Adzuna".
    """

    name = "adzuna"
    BASE = "https://api.adzuna.com/v1/api/jobs/in/search"

    def __init__(self, client: httpx.Client | None = None):
        self._client = client

    def is_configured(self) -> bool:
        s = get_settings()
        return bool(s.adzuna_app_id and s.adzuna_app_key)

    def fetch(self, query: str, location: str = "", page: int = 1) -> list[NormalizedJob]:
        if not self.is_configured():
            raise SourceNotConfigured("Set ADZUNA_APP_ID and ADZUNA_APP_KEY to enable Adzuna")
        s = get_settings()
        params = {
            "app_id": s.adzuna_app_id,
            "app_key": s.adzuna_app_key,
            "results_per_page": 50,
            "what": query,
            "max_days_old": 30,
            "sort_by": "date",
            "content-type": "application/json",
        }
        if location:
            params["where"] = location
        client = self._client or httpx.Client(timeout=20)
        try:
            r = client.get(f"{self.BASE}/{page}", params=params)
        except httpx.HTTPError as e:
            raise SourceError(f"Adzuna unreachable: {type(e).__name__}") from e
        finally:
            if self._client is None:
                client.close()
        if r.status_code in (401, 403):
            raise SourceError("Adzuna rejected the API keys. Check ADZUNA_APP_ID and ADZUNA_APP_KEY.")
        if r.status_code == 429:
            raise SourceError("Adzuna rate limit reached; the next refresh will retry.")
        if r.status_code >= 400:
            raise SourceError(f"Adzuna returned HTTP {r.status_code}")
        try:
            results = r.json().get("results", [])
        except ValueError as e:
            raise SourceError("Adzuna returned something that isn't JSON") from e
        return [j for j in (normalize_adzuna(x) for x in results) if j]


REGISTRY: dict[str, JobSource] = {s.name: s for s in (SeedJobSource(), AdzunaJobSource())}
