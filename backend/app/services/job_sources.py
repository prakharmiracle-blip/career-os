"""JobSource adapter interface.

Every external provider (Adzuna, JSearch, Jooble) implements `JobSource.fetch()` and
returns normalised `NormalizedJob` records, which an ingest job upserts into `jobs`
keyed on (source, external_id). The app always reads from our own DB, so it works
offline with seed data and never depends on a provider being up.

Phase 1 ships the interface, the seed source, and an Adzuna adapter that is disabled
until ADZUNA_APP_ID / ADZUNA_APP_KEY are set. Only use providers' official APIs and
respect their terms; no scraping.
"""

from __future__ import annotations

from abc import ABC, abstractmethod
from dataclasses import dataclass, field
from datetime import datetime

from app.config import get_settings


@dataclass
class NormalizedJob:
    source: str
    external_id: str
    title: str
    company: str
    location: str
    work_mode: str
    job_type: str
    salary_min_lpa: int
    salary_max_lpa: int
    exp_min: int
    exp_max: int
    description: str
    posted_at: datetime
    responsibilities: list[str] = field(default_factory=list)
    skills: list[str] = field(default_factory=list)


class SourceNotConfigured(RuntimeError):
    pass


class JobSource(ABC):
    name: str

    @abstractmethod
    def is_configured(self) -> bool: ...

    @abstractmethod
    def fetch(self, query: str, location: str, page: int = 1) -> list[NormalizedJob]: ...


class SeedJobSource(JobSource):
    """Offline source: generated by app.seed. Always available."""

    name = "seed"

    def is_configured(self) -> bool:
        return True

    def fetch(self, query: str, location: str, page: int = 1) -> list[NormalizedJob]:
        from app.seed import generate_jobs

        return [j for j in generate_jobs() if query.lower() in j.title.lower()][(page - 1) * 50 : page * 50]


class AdzunaJobSource(JobSource):
    """https://developer.adzuna.com/ — implemented in Phase 2 ingest."""

    name = "adzuna"

    def is_configured(self) -> bool:
        s = get_settings()
        return bool(s.adzuna_app_id and s.adzuna_app_key)

    def fetch(self, query: str, location: str, page: int = 1) -> list[NormalizedJob]:
        if not self.is_configured():
            raise SourceNotConfigured("Set ADZUNA_APP_ID and ADZUNA_APP_KEY to enable Adzuna")
        raise NotImplementedError("Adzuna ingest lands in Phase 2")


REGISTRY: dict[str, JobSource] = {s.name: s for s in (SeedJobSource(), AdzunaJobSource())}


def available_sources() -> list[dict]:
    return [{"name": n, "configured": s.is_configured()} for n, s in REGISTRY.items()]
